from __future__ import annotations

import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.cli import HELP
from app.modes import ExecutionMode
from app.runtime import build_runtime


TARGET = PROJECT_ROOT / "docs/generated/runtime-reference.md"


def render() -> str:
    runtime = build_runtime(use_model=False, start_background_services=False)
    try:
        tools = runtime.registry.describe()
    finally:
        runtime.close()
    lines = [
        "# Generated runtime reference", "",
        "> Generated by `scripts/generate_reference.py` from the CLI, mode enum, and live tool registry. Do not hand-edit.",
        "", "## Commands", "", "```text", HELP.strip(), "```", "", "## Modes", "",
    ]
    lines.extend(f"- `{mode.value}`" for mode in ExecutionMode)
    lines.extend(["", f"## Model-independent tools ({len(tools)})", "", "> A configured vision provider adds the conditional `analyze_screenshot` tool at normal startup.", "", "| Tool | Risk | Permission | Description |", "|---|---|---|---|"])
    for tool in tools:
        description = str(tool["description"]).replace("|", "\\|").replace("\n", " ")
        lines.append(f"| `{tool['name']}` | {tool['risk']} | `{tool['permission']}` | {description} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
            print(f"Generated documentation is stale: {TARGET}")
            return 1
        print(f"Generated documentation is current: {TARGET}")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
