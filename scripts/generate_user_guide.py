"""Write docs/how-to-use-hayat.md from HAYAT's own capability catalog.

The guide is generated so it cannot drift from what HAYAT can actually do:
every area in app/capabilities.py appears with what it does, how it works,
words to say, and the window to open. tests/test_plain_output.py fails when
the file is out of date; run this script to refresh it.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

TARGET = ROOT / "docs" / "how-to-use-hayat.md"

INTRO = """# How to use HAYAT

> Generated by `scripts/generate_user_guide.py` from HAYAT's capability catalog. Do not hand-edit.

HAYAT is a private assistant that runs on your own Windows computer. You talk to it in plain words, typed or
spoken, and it decides which of its tools to use. Nothing leaves your computer unless you ask for it.

## The basics

1. **Start it.** Run `python run.py` (or the HAYAT shortcut). The main window opens with the chat in the middle.
2. **Ask in your own words.** Type in the box at the bottom and press **Enter** (Shift+Enter for a new line), or
   press **Mic** and speak. You never need special commands; the phrases below are examples, not rules.
3. **Watch it work.** Long jobs (searches, videos, research) run in the background. HAYAT tells you it has
   started, keeps chatting, and reports back when it is done. The **Activity** tab shows every step it took.
4. **Stay in control.** Anything that acts on the outside world (sending an email, posting, buying, signing in)
   waits for your **Approve**. **Stop reply** ends the current answer; the red **Emergency stop** halts all work.
5. **Find any window.** **All features** lists every area below; **Studios ▾** opens the full windows; press
   **Ctrl+`** to switch between open windows; **What can HAYAT do?** answers from this same catalog.
6. **When something fails,** HAYAT says what failed and why in plain words. Say "search again", "try again" or
   "what went wrong?" to continue.

On the command line (`python run.py --cli-only`) the same requests work, and slash commands such as `/health`
print plain lines. Set `HAYAT_CLI_JSON=1` if a script needs JSON instead.

## Everything HAYAT can do
"""


def render() -> str:
    from app.capabilities import CATALOG

    lines = [INTRO]
    lines.append("| Area | What it does |\n| --- | --- |")
    for capability in CATALOG:
        anchor = capability.key.replace("_", "-")
        summary = " ".join(capability.summary.split()).replace("|", "/")
        lines.append(f"| [{capability.title}](#{anchor}) | {summary} |")
    lines.append("")
    for capability in CATALOG:
        lines.append(f'<a id="{capability.key.replace("_", "-")}"></a>\n')
        lines.append(f"### {capability.title}\n")
        lines.append(" ".join(capability.summary.split()) + "\n")
        if capability.how:
            lines.append("**How it works:** " + " ".join(capability.how.split()) + "\n")
        if capability.examples:
            lines.append("**Try saying:**\n")
            lines += [f"- “{example}”" for example in capability.examples]
            lines.append("")
        if capability.opens_label:
            lines.append(f"**Window:** {capability.opens_label}\n")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
