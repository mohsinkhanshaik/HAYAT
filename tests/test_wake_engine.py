def test_the_recorder_stops_at_the_first_detected_frame(monkeypatch):
    from app.voice.microphone import MicrophoneRecorder

    class _Stream:
        def __init__(self, callback=None, blocksize=0, **kwargs):
            self.callback, self.blocksize = callback, blocksize

        def __enter__(self):
            for _ in range(5):
                self.callback(np.full((self.blocksize, 1), 0.5, dtype=np.float32), self.blocksize, None, None)
            return self

        def __exit__(self, *exc):
            return False

    recorder = MicrophoneRecorder.__new__(MicrophoneRecorder)
    recorder.sample_rate, recorder.channels, recorder.device = 16000, 1, None
    monkeypatch.setattr(recorder, "_require_input", lambda: None)
    monkeypatch.setattr(recorder, "_sounddevice", lambda: SimpleNamespace(InputStream=_Stream))
    seen = []

    def detect(frame):
        seen.append(frame)
        return len(seen) == 3

    assert recorder.listen_for(detect, threading.Event(), timeout=2) is True
    assert len(seen) == 3 and seen[0].dtype == np.int16 and seen[0][0] == 16383


def test_the_voice_loop_records_the_command_only_after_the_wake_word():
    from app.voice.manager import VoiceManager

    submitted, spoken = [], []
    manager = VoiceManager.__new__(VoiceManager)
    manager.wake_gate = OpenWakeWordGate(factory=lambda: _Engine([0.9]))
    manager.cancellation = SimpleNamespace(shutdown=threading.Event())
    manager.recorder = SimpleNamespace(
        listen_for=lambda detect, cancel, timeout=None: detect(np.zeros(1280, dtype=np.int16)),
        record_until_silence=lambda *a: SimpleNamespace(samples=np.ones(8000)),
    )
    manager.transcribe = lambda audio: SimpleNamespace(text="open notepad")
    manager.submit_transcript = submitted.append
    manager._speak = spoken.append
    manager._log = lambda *a, **k: None
    manager._gated_wake_cycle({})
    assert spoken == ["Yes?"] and submitted == ["open notepad"]


def _clip(name):
    path = CLIPS / name
    if not path.is_file():
        pytest.skip("synthesised wake clips are generated by the wake verification run")
    with wave.open(str(path), "rb") as source:
        rate = source.getframerate()
        samples = np.frombuffer(source.readframes(source.getnframes()), dtype="<i2").astype(np.float32)
    if rate != 16000:
        samples = np.interp(np.linspace(0, len(samples), int(len(samples) * 16000 / rate), endpoint=False),
                            np.arange(len(samples)), samples)
    return np.concatenate([np.zeros(16000), samples, np.zeros(16000)]).astype(np.int16)


def test_the_real_model_hears_hey_jarvis_and_ignores_other_speech():
    gate = OpenWakeWordGate("hey_jarvis")
    if not gate.ready()[0]:
        pytest.skip("hey_jarvis model not downloaded")
    for name, expected in (("clip0.wav", True), ("clip2.wav", False)):
        audio, detect = _clip(name), gate.detector()
        heard = any(detect(audio[i:i + 1280]) for i in range(0, len(audio) - 1280, 1280))
        assert heard is expected, name
