from app.voice.wake_engine import OpenWakeWordGate

CLIPS = Path(__file__).resolve().parents[1] / ".test-runs" / "wake"


class _Engine:
    def __init__(self, scores):
        self.scores, self.resets = list(scores), 0

    def reset(self):
        self.resets += 1

    def predict(self, frame):
        return {"wake": self.scores.pop(0) if self.scores else 0.0}


def test_the_gate_fires_only_above_its_threshold():
    engine = _Engine([0.1, 0.4, 0.8])
    gate = OpenWakeWordGate("hey_jarvis", threshold=0.5, factory=lambda: engine)
    detect = gate.detector()
    frame = np.zeros(1280, dtype=np.int16)
    assert [detect(frame) for _ in range(3)] == [False, False, True]
    assert engine.resets == 1, "each wait starts from a clean model state"


